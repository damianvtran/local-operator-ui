// Scoped recovery of the native card artifact, NOT a whole-app build.
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root = process.cwd();
const require = createRequire(join(root, 'package.json'));
const { resolveConfig } = await import(pathToFileURL(require.resolve('electron-vite')).href);
const { build } = await import(pathToFileURL(require.resolve('vite')).href);
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const walk = (dir) => readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(join(dir,e.name)) : [join(dir,e.name)]);
const tree = (dir) => Object.fromEntries(walk(dir).sort().map(p => [p.slice(root.length+1),hash(readFileSync(p))]));
const before = { main:tree(resolve('out/main')), preload:tree(resolve('out/preload')) };
const preload = 'out/preload/browser-approvals-overlay.js';
assert.equal(before.preload[preload], '9497956e0e76f8cabd4d840cdf11f3351553963482c354bf09f54a5117602ffe', 'must match known-good before preload artifact');
const sourcePaths = ['src/main/browser/approvals-overlay.ts','src/renderer/src/approvals-overlay/main.ts','src/renderer/src/approvals-overlay/card.css','src/renderer/browser-approvals-overlay.html','src/preload/browser-approvals-overlay.ts','src/shared/browser-approvals-overlay.ts','electron.vite.config.js'];
const receipt = {scope:'Native card entry only. out/main is not used by the native probe; probe main is bundled from frozen controller source per cell. No whole-app proof.', head:execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(), dirtyPatchSha256:hash(execFileSync('git',['diff','--binary','HEAD'])), source:Object.fromEntries(sourcePaths.map(p => [p,hash(readFileSync(p))])), before};
writeFileSync(process.env.RECEIPT,JSON.stringify(receipt,null,2));
process.env.NODE_ENV_ELECTRON_VITE='production';
const resolved=await resolveConfig({configFile:resolve('electron.vite.config.js')},'build','production');
assert.ok(resolved.config?.renderer);
const renderer=resolved.config.renderer;
const input={approvalsOverlay:resolve('src/renderer/browser-approvals-overlay.html')};
renderer.input=input;
renderer.build={...renderer.build,outDir:resolve('out/renderer'),emptyOutDir:false,rollupOptions:{...renderer.build.rollupOptions,input}};
receipt.build={input, outDir:renderer.build.outDir, emptyOutDir:false, config:resolved.configFile, plugins:renderer.plugins.flat().map(p=>p?.name).filter(Boolean)};
console.log(JSON.stringify(receipt.build));
await build(renderer);
const after={main:tree(resolve('out/main')),preload:tree(resolve('out/preload'))};
assert.deepEqual(after,before,'renderer-only build must not write main/preload');
for (const [p,expected] of Object.entries(receipt.source)) assert.equal(hash(readFileSync(p)),expected,`source changed during build: ${p}`);
receipt.after=after;
const html=resolve('out/renderer/browser-approvals-overlay.html');
const files=[html,...[...readFileSync(html,'utf8').matchAll(/(?:src|href)="([^"\s]+\.(?:js|css))"/g)].map(m=>resolve('out/renderer',m[1]))];
receipt.artifacts=Object.fromEntries(files.map(p=>[p.slice(root.length+1),hash(readFileSync(p))]));
receipt.completedAt=new Date().toISOString();
writeFileSync(process.env.RECEIPT,JSON.stringify(receipt,null,2));
console.log('CARD BUILD VERIFIED: main/preload byte-identical, source unchanged, card artifact hashes recorded');
