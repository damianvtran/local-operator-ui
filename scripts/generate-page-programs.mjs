#!/usr/bin/env node
/**
 * The writer (and `--check` gate) for
 * `src/main/browser/actions/page-programs.gen.ts`.
 *
 * WHY THIS EXISTS — the measurement, not a preference, and the same one
 * `generate-geometry-sources.mjs` records. The host injects its page functions
 * into a tab as SOURCE. The original shape for `select` was
 * `({fn}.toString()) at runtime`, which works in dev and in the test bundle and
 * CANNOT work in a built app: `pnpm build` compiles the main bundle to V8
 * bytecode (`out/main/index.jsc`), and the bytecode loader executes it against a
 * DUMMY source string (zero-width spaces, length-matched to the original), so
 * `Function.prototype.toString()` returns the dummy text. Measured on this
 * branch's bytecode build: `select` answered "selection target disappeared
 * during selection" for every call, because CDP was handed the dummy as the
 * program.
 *
 * So the source text is captured HERE, at generation time, from the one readable
 * implementation in `actions/page-programs/`, and committed as string constants.
 * The app injects those constants. No second copy of the logic: the constants
 * ARE these modules' own text, and `check-page-programs.test.mjs` re-derives
 * this file and fails when it is stale.
 *
 * WHY A SECOND GENERATOR RATHER THAN A ROW IN THE GEOMETRY ONE: that script's
 * contract is "derived from the PROVENANCE-pinned vendored driver, hash in the
 * header". These programs are APP-owned (the extension implements the same two
 * verbs its own way), so folding them in would make one file claim a provenance
 * it does not have. The technique is deliberately identical; only the source of
 * truth differs, and each output file names its own.
 *
 * Usage:
 *   node scripts/generate-page-programs.mjs           # write the file
 *   node scripts/generate-page-programs.mjs --check   # fail if stale
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { transform } from "esbuild";
import { isEntryPoint } from "./entry-point.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The readable implementations the constants are captured from. */
export const PROGRAMS_DIR = join(
	ROOT,
	"src",
	"main",
	"browser",
	"actions",
	"page-programs",
);

/** Where the generated constants live. */
export const OUTPUT_PATH = join(
	ROOT,
	"src",
	"main",
	"browser",
	"actions",
	"page-programs.gen.ts",
);

/** The functions that cross into a page, the module each lives in, and the
 *  constant each becomes. `file` is explicit per export for the reason its
 *  sibling gives: one hardcoded path is how a new page function silently keeps
 *  being generated from the old file. */
const EXPORTS = [
	{ file: "select-page.ts", fn: "selectPage", constant: "SELECT_PAGE_SOURCE" },
	{
		file: "setvalue-page.ts",
		fn: "setvaluePage",
		constant: "SETVALUE_PAGE_SOURCE",
	},
];

/**
 * Re-derive the generated file's exact text, plus the hash of the modules it
 * came from. Pure over those files: the caller decides whether to write it or
 * compare it.
 */
export async function renderPrograms(options = {}) {
	const programsDir = options.programsDir ?? PROGRAMS_DIR;
	const modules = new Map();
	const sources = new Map();
	for (const { file } of EXPORTS) {
		if (modules.has(file)) continue;
		const source = readFileSync(join(programsDir, file), "utf8");
		sources.set(file, source);
		// The same transpiler the test bundle runs, configured the same way
		// (`format: "esm"`, TS loader), so the captured text is what a modern
		// engine executes unchanged.
		const compiled = await transform(source, { loader: "ts", format: "esm" });
		modules.set(
			file,
			await import(
				`data:text/javascript;base64,${Buffer.from(compiled.code).toString("base64")}`
			),
		);
	}
	const values = EXPORTS.map(({ file, fn, constant }) => {
		const value = String(modules.get(file)[fn]);
		if (!value.includes("=>") && !value.startsWith("function ")) {
			throw new Error(
				`${fn} did not transpile to a function (got ${value.slice(0, 40)}...)`,
			);
		}
		return { constant, value };
	});
	const hash = createHash("sha256")
		.update(
			[...sources.entries()]
				.sort(([left], [right]) => left.localeCompare(right))
				.map(([file, source]) => `${file}\u0000${source}`)
				.join("\u0000"),
		)
		.digest("hex");
	const header = [
		"// GENERATED by scripts/generate-page-programs.mjs — do not edit by hand.",
		`// Source of truth: src/main/browser/actions/page-programs/{select-page,setvalue-page}.ts (sha256 ${hash}).`,
		"// Regenerate with that script; check-page-programs.test.mjs fails when this",
		"// file and those modules disagree.",
		"//",
		"// WHY THE SOURCE IS COMMITTED AS STRINGS: the packaged main bundle is V8",
		"// bytecode, and its loader runs the script against a dummy source string, so",
		"// `Function.prototype.toString()` returns that dummy text — measured, and the",
		'// reason every `select` call answered "selection target disappeared during',
		"// selection\" on the shipped build. These constants carry the same functions'",
		"// own source into the page; the modules beside them stay the readable",
		"// implementations.",
	].join("\n");
	const body = values
		.map(
			({ constant, value }) =>
				`export const ${constant} = ${JSON.stringify(value)};`,
		)
		.join("\n\n");
	return { text: `${header}\n\n${body}\n`, hash };
}

async function main() {
	const check = process.argv.includes("--check");
	const { text } = await renderPrograms();
	let onDisk = "";
	try {
		onDisk = readFileSync(OUTPUT_PATH, "utf8");
	} catch {
		/* missing is stale */
	}
	if (check) {
		if (onDisk !== text) {
			console.error(
				"page-programs: STALE — src/main/browser/actions/page-programs.gen.ts " +
					"does not match what the generator derives from actions/page-programs/.",
			);
			console.error("  fix: node scripts/generate-page-programs.mjs");
			process.exitCode = 1;
			return;
		}
		console.log(
			"page-programs: the generated sources match the page programs.",
		);
		return;
	}
	if (onDisk === text) {
		console.log("page-programs: already fresh; nothing written.");
		return;
	}
	writeFileSync(OUTPUT_PATH, text);
	console.log(
		`page-programs: wrote ${OUTPUT_PATH} (${text.length} bytes) from ${PROGRAMS_DIR}`,
	);
}

if (isEntryPoint(import.meta.url)) {
	main().catch((error) => {
		console.error(`page-programs: FAILED to run: ${error.message}`);
		process.exitCode = 1;
	});
}
